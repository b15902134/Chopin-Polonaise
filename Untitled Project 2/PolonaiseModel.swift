@MainActor
@Observable
final class PolonaiseLibrary {
    var query = "" {
        didSet { refresh() }
    }

    var selectedPeriod = "全部" {
        didSet { refresh() }
    }

    let periods = ["全部", "童年時期", "華沙少年期", "華沙青年期", "華沙末期", "維也納／巴黎初期", "巴黎成熟期", "馬約卡時期", "晚期"]
    private(set) var visibleChapters = PolonaiseCatalog.chapters.sorted { $0.year < $1.year }

    private func refresh() {
        visibleChapters = PolonaiseCatalog.chapters
            .filter { chapter in
                let matchesQuery = query.isEmpty
                    || chapter.title.localizedCaseInsensitiveContains(query)
                    || chapter.originalTitle.localizedCaseInsensitiveContains(query)
                    || chapter.catalog.localizedCaseInsensitiveContains(query)
                let matchesPeriod = selectedPeriod == "全部" || chapter.period == selectedPeriod
                return matchesQuery && matchesPeriod
            }
            .sorted { $0.year < $1.year }
    }
}

@MainActor
@Observable
final class PolonaiseFavorites {
    private static let key = "favoritePolonaiseChapterIDs"

    var ids: Set<String> = [] {
        didSet { UserDefaults.standard.set(Array(ids), forKey: Self.key) }
    }

    init() {
        ids = Set(UserDefaults.standard.stringArray(forKey: Self.key) ?? [])
    }

    func contains(_ id: String) -> Bool { ids.contains(id) }

    func toggle(_ id: String) {
        if ids.contains(id) {
            ids.remove(id)
        } else {
            ids.insert(id)
        }
    }
}
