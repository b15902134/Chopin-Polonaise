    var interpretationComparison: String {
        switch period {
        case "童年時期", "華沙少年期":
            "古典取向的演奏會保留清楚拍點、輕巧裝飾音與舞步比例，讓少年作品的沙龍氣質自然顯現；浪漫取向則會放寬句尾速度、加深內聲部，使尚未完全成熟的篇幅多一層回憶感。比較版本時，最值得注意的不是誰更快，而是演奏者是否能在自由速度之中維持波蘭舞曲第三拍的支撐。"
        case "華沙青年期", "華沙末期":
            "結構型演奏傾向以穩定速度與清晰低音維持長線，凸顯作品由舞曲走向音樂廳的規模；敘事型演奏則強調段落轉折、音色遠近與突然的停頓，把離鄉前後的心理張力置於前景。理想的詮釋需要同時保有公共姿態與私密語氣，避免只剩外在炫技。"
        case "維也納／巴黎初期", "馬約卡時期":
            "華麗型版本常突出八度、強奏與快速音群的光澤；內省型版本則降低表面重量，讓和聲陰影與旋律呼吸更清楚。兩者沒有唯一答案，但踏板若過度飽滿，容易掩蓋舞曲節奏；若過度節制，又會失去蕭邦特有的歌唱性。"
        default:
            "晚期作品可採建築式詮釋，以穩定脈動組織龐大曲式；也可採詩性詮釋，藉觸鍵層次、時間伸縮與聲部遠近塑造記憶感。成熟版本通常不把英雄性等同於巨大音量，而是在高潮前保留動態空間，並讓中段抒情材料與主題形成真正的敘事對話。"
        }
    }

    var samePeriodWorks: [PolonaiseChapter] {
        PolonaiseCatalog.chapters
            .filter { $0.period == period && $0.id != id }
            .sorted { $0.year < $1.year }
    }
}
