        case "05": "1841 年出版"
        case "06": "1843 年出版"
        case "07": "1846 年出版"
        case "08", "09": "1836 年以 Op. 22 合併出版"
        case "10", "11", "12": "1855 年身後以 Op. 71 出版"
        case "13": "1817 年刊行"
        case "19": "1831 年出版；約作於 1829–1830 年"
        default: "生前未正式出版；後由手稿整理刊行"
        }
    }

    var titleAttribution: String {
        switch id {
        case "03":
            "〈軍隊〉為後世通稱，並非蕭邦親題。"
